// baltacı yetenekleri eski ikonlarını kullanır
const ALIAS = { ab_wave: 'wave', ab_ring: 'ring', ab_veil: 'veil', ab_wrath: 'wrath' };
export const ICON_IDS = Object.keys(I);
// düğüm → ikon: yetenek düğümü yeteneğin ikonunu, diğerleri sınıfa uygun ikonu kullanır
const NODE_ICON = {
  draw: 'bow', rapid: 'rapid', multi: 'multi', fleet: 'stride', sidestep: 'dash', dodge: 'dodge', flameArrow: 'flameArrow', hotTip: 'hotTip',
  blast: 'blast', scorch: 'orb', chill: 'cold', freeze: 'freeze', thrift: 'thrift', ashgain: 'yield', inner: 'warm', ashheart: 'heart',
};
export function nodeIcon(n) { return n.ability ? 'ab_' + n.ability : NODE_ICON[n.id] || n.icon || n.id; }

// icon(id, mode): mode 'n' normal, 'd' karanlık (kilitli siluet), 'g' gri
export function icon(id, mode = 'n') {
  return cached('ic' + id + mode, 12, 12, (x) => {
    const rows = I[id] || I[ALIAS[id]] || I.star;
    let p = new Pix(12, 12);
    p.grid(rows, 1, 1, CH);
    if (mode === 'd') p = p.silhouette(PAL.C3);
    else if (mode === 'g') p = p.map(c => (c === PAL.E6 || c === PAL.E5 || c === PAL.A3 ? PAL.A1 : PAL.A0));
    p.outline(PAL.C0);
    p.drawTo(x);
  });
}
